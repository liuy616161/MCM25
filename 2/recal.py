def load_and_process_data(data_text):
    """从文本加载数据并重新计算有效遮蔽时长"""
    # 从文本创建DataFrame
    lines = data_text.strip().split('\n')
    # 解析表头和数据
    header = lines[0].split('\t')
    data = []
    for line in lines[1:]:
        values = line.split('\t')
        data.append(values)
    
    df = pd.DataFrame(data, columns=header)
    
    # 转换数据类型
    for col in ['direction', 'speed', 'release_time', 'detonation_delay', 'effective_duration']:
        df[col] = pd.to_numeric(df[col])
    
    # 创建结果目录
    results_dir = "recalculation_results"
    if not os.path.exists(results_dir):
        os.makedirs(results_dir)
    
    # 重新计算每个参数组合的有效遮蔽时长
    results = []
    for i, row in df.iterrows():
        print(f"处理参数组合 {i+1}/{len(df)}...")
        
        # 提取参数
        direction = row['direction']
        speed = row['speed']
        release_time = row['release_time']
        detonation_delay = row['detonation_delay']
        
